#!/usr/bin/env python3
"""Generate SideStore/Design/SiloLook.swift from the Silo design tokens.

    python3 scripts/design/gen_tokens.py [path/to/silo-cloud/packages/design/tokens.json]

Dark uses the "layers" look, light uses "front", as on Silo's other native clients.
"""

import json
import re
import sys
from pathlib import Path

DEFAULT_TOKENS = Path.home() / "Projects/silo-cloud/packages/design/tokens.json"
OUT = Path(__file__).resolve().parents[2] / "SideStore/Design/SiloLook.swift"

COLORS = [
    ("ground", "elev0"),
    ("surface", "elev1"),
    ("raised", "elev2"),
    ("raisedStrong", "elev3"),
    ("border", "border"),
    ("borderStrong", "borderStrong"),
    ("text", "text"),
    ("textMuted", "textMuted"),
    ("textFaint", "textFaint"),
    ("accent", "primary"),
    ("accentInk", "primaryInk"),
    ("accentMuted", "accentMuted"),
    ("danger", "danger"),
    ("ok", "ok"),
    ("warn", "warn"),
]
RADII = [("radiusPanel", "rPanel"), ("radiusRow", "rRow"), ("radiusControl", "rControl")]


# Silo Store's dark look: a neutral charcoal ramp instead of the Layers teal.
# Accent, danger, ok and warn stay Silo's.
IOS_DARK = {
    "elev0": "#141416",
    "elev1": "#1B1B1E",
    "elev2": "#232327",
    "elev3": "#2C2C31",
    "border": "#2E2E33",
    "borderStrong": "#5A5A62",
    "text": "#F4F4F5",
    "textMuted": "#B8B8BE",
    "textFaint": "#8E8E95",
    "primary": "#22B9CC",
    "primaryInk": "#0A0A0B",
    "accentMuted": "#17363B",
}


def hex_literal(value: str) -> str:
    if not re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
        raise SystemExit(f"expected a #RRGGBB colour, got {value!r}")
    return "0x" + value[1:].upper()


def px(value: str) -> str:
    return str(int(float(value.replace("px", ""))))


def look(name: str, theme: dict) -> str:
    lines = [f"    static let {name} = SiloLook("]
    for swift_name, token in COLORS:
        lines.append(f"        {swift_name}: UIColor(siloHex: {hex_literal(theme[token])}),")
    for swift_name, token in RADII:
        lines.append(f"        {swift_name}: {px(theme[token])},")
    lines.append(f"        displayWeight: {int(theme['weightDisplay'])}")
    lines.append("    )")
    return "\n".join(lines)


def main():
    tokens_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_TOKENS
    themes = json.loads(tokens_path.read_text(encoding="utf-8"))["theme"]
    themes["layers"] = {**themes["layers"], **IOS_DARK}

    fields = [f"    let {n}: UIColor" for n, _ in COLORS]
    fields += [f"    let {n}: CGFloat" for n, _ in RADII]
    fields += ["    let displayWeight: CGFloat"]

    out = f"""//
//  SiloLook.swift
//  Silo Store
//
//  Generated by scripts/design/gen_tokens.py from silo-cloud/packages/design/tokens.json.
//  Do not edit by hand: change the tokens and run the script again.
//

import UIKit

struct SiloLook {{
{chr(10).join(fields)}
}}

extension SiloLook {{
    /// Dark: neutral charcoal ground, bright cyan accent, rounded.
{look("layers", themes["layers"])}

    /// Light: paper and ink, square.
{look("front", themes["front"])}
}}

extension UIColor {{
    convenience init(siloHex hex: UInt32) {{
        self.init(
            red: CGFloat((hex >> 16) & 0xFF) / 255,
            green: CGFloat((hex >> 8) & 0xFF) / 255,
            blue: CGFloat(hex & 0xFF) / 255,
            alpha: 1
        )
    }}
}}
"""
    OUT.write_text(out, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
